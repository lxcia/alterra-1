"""Write every prompt string used in the experiments, verbatim from the code, to writeup/prompts.md.

Run: python src/dump_prompts.py
"""
import ast
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent
sys.path.insert(0, str(SRC / "experiments"))
import common  # noqa: E402  (sets sys.path for src/)
from pipeline import INSTRUCTION, SEQ_DESC  # noqa: E402

OUT = SRC.parent / "writeup" / "prompts.md"


def literal_assignments(path: Path, names: list[str]) -> dict:
    """Evaluate the named module-level assignments of a script (found with ast) without running
    the script itself (which would parse argv and load models)."""
    ns = {"FINAL_YN": common.FINAL_YN, "Q_ENDO": common.Q_ENDO, "Q_SIDE": common.Q_SIDE}
    tree = ast.parse(path.read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) in names for t in node.targets):
            exec(compile(ast.Module([node], []), str(path), "exec"), ns)
    return {n: ns[n] for n in names if n in ns}


def block(title: str, text) -> str:
    if isinstance(text, dict):
        return f"### {title}\n" + "\n".join(f"- `{k}`: {v!r}" for k, v in text.items()) + "\n"
    if isinstance(text, list):
        return f"### {title}\n" + "\n".join(f"{i}. {t!r}" for i, t in enumerate(text)) + "\n"
    return f"### {title}\n```\n{text}\n```\n"


E = SRC / "experiments"
parts = ["# Prompts (verbatim, generated by src/dump_prompts.py)\n",
         "Message layout (Google CT notebook): `[instruction] + [image, \"SLICE n\"] x N + [query]`, "
         "where N <= 85 slices. Histories / convention statements are appended to the instruction.\n",
         block("Reference instruction template", INSTRUCTION),
         block("Sequence descriptions", SEQ_DESC),
         block("Q_ENDO (endometrioma yes/no)", common.Q_ENDO),
         block("Q_SIDE (side of dominant lesion)", common.Q_SIDE),
         block("Q_TYPE (lesion type)", common.Q_TYPE)]
parts.append(block("expB histories", literal_assignments(E / "expB_history.py", ["HISTORIES"])["HISTORIES"]))
parts.append(block("expB2 histories", literal_assignments(E / "expB2_history_dose.py", ["HIST"])["HIST"]))
parts.append(block("expC convention statements", literal_assignments(E / "expC_laterality.py", ["CONVENTIONS"])["CONVENTIONS"]))
c3 = literal_assignments(E / "expC3_side_prompt.py", ["Q_ORDER_RL", "Q_OPEN", "Q_YN"])
for k, v in c3.items():
    parts.append(block(f"expC3 {k}", v))
parts.append(block("expC2 Q_CYST", literal_assignments(E / "expC2_synthetic_side.py", ["Q_CYST"])["Q_CYST"]))
n = literal_assignments(E / "expN_noise.py", ["ENDO_PARA", "SIDE_TAIL", "SIDE_PARA"])
parts.append(block("expN endometrioma paraphrases", n["ENDO_PARA"]))
parts.append(block("expN side paraphrases", n["SIDE_PARA"]))
f = literal_assignments(E / "expF_pushback.py", ["PUSH", "NEUTRAL"])
parts.append(block("expF pushback turns", {**f["PUSH"], "neutral": f["NEUTRAL"]}))
OUT.write_text("\n".join(parts))
print("wrote", OUT)
